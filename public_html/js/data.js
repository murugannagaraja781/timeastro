function renderKadigaram() {
    const nakshatraWheel = document.getElementById('nakshatra-wheel');
    const rasiWheel = document.getElementById('rasi-wheel');
    
    if(!nakshatraWheel || !rasiWheel) return;

    // Render 27 Nakshatras in a circle
    let nakshatraHtml = '';
    const total = 27;
    const angleStep = 360 / total;

    websiteData.nakshatras.forEach((nak, index) => {
        // We offset by 90 degrees to start at 12 o'clock if needed, 
        // but default CSS transform handles it fine if we just rotate.
        const rotation = index * angleStep;
        nakshatraHtml += `
            <div class="nakshatra-segment" style="transform: translateX(-50%) rotate(${rotation}deg);">
                <div class="nakshatra-tick"></div>
                <div class="nakshatra-text">${nak}</div>
            </div>
        `;
    });
    
    // Add the glowing clock hand
    nakshatraHtml += `<div class="clock-hand"></div>`;
    nakshatraWheel.innerHTML = nakshatraHtml;

    // Render 12 Rasis in the inner circle
    let rasiHtml = '';
    const rasiStep = 360 / 12;
    websiteData.rasis.forEach((rasi, index) => {
        const rotation = index * rasiStep;
        // Adjusting text rotation to be upright or outward pointing
        rasiHtml += `
            <div class="rasi-segment" style="transform: translateX(-50%) rotate(${rotation}deg);">
                <div class="rasi-content">
                    <span class="rasi-text">${rasi.name}</span>
                </div>
            </div>
        `;
    });
    rasiWheel.innerHTML = rasiHtml;

    // Insert ONLY the rasi wheel container (Planetary hands removed as requested)
    rasiWheel.innerHTML = rasiHtml;
}

